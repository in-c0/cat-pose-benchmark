"""One generated source of truth for every number the notes quote (pass 19).

Scores v1 / v3 / v3a on the development clips, holdout #1 and holdout #2, each twice —
``adjudicated`` (current truth + hand overrides) and ``as_frozen`` (the same truth file but
automatic judgements only, no overrides) — and writes

    review/truth/methods/aggregate.json   every count, per clip and pooled
    review/truth/methods/aggregate.md     the tables the notes should copy from

Frame-level (micro) precision/recall are reported with clip-level views alongside: per-clip
counts, a macro average over clips that have at least one primary positive (recall) or at
least one assertion (precision), and the number of distinct false *runs* (maximal sets of
consecutive false frames in one clip), because 17 rump frames are one mistake.

    python -m review.aggregate
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from review.score_truth import TRUTH, frame_class, judge, load_overrides, load_truth, tally

METHODS = ("tail_grounded_v1", "tail_grounded_v3", "tail_grounded_v3a")
SETS = {"dev": ("frames.csv", ""), "holdout1": ("holdout_frames.csv", "+holdout"), "holdout2": ("holdout2_frames.csv", "+holdout2")}
WRONG = ("wrong_part", "wrong_cat", "unusable_curve")


def false_runs(rows: list[dict], truth: dict) -> int:
    """Number of maximal runs of consecutive frames (per clip) on which the method's
    assertion counts as false (FPv or FPn)."""
    by_clip: dict[str, list[int]] = defaultdict(list)
    for r in rows:
        t = truth[(r["clip_id"], r["frame_index"])]
        if frame_class(t) != "ambiguous" and r["output_status"] in WRONG:
            by_clip[r["clip_id"]].append(r["frame_index"])
    n = 0
    for frames in by_clip.values():
        frames.sort()
        n += 1 + sum(1 for a, b in zip(frames, frames[1:]) if b != a + 1)
    return n


def score(method: str, set_name: str, use_overrides: bool) -> dict:
    truth_file, suffix = SETS[set_name]
    truth = load_truth(truth_file)
    overrides = load_overrides()
    tag = method + suffix
    per_clip = {}
    all_rows = []
    for clip in sorted({k[0] for k in truth}):
        rows = judge(method, clip, clip, 1, truth, overrides, tag, use_overrides=use_overrides)
        if not rows:
            continue
        all_rows += rows
        per_clip[clip] = tally(rows, truth)
    pooled = tally(all_rows, truth)
    pooled["false_runs"] = false_runs(all_rows, truth)
    pooled["frames_scored"] = len(all_rows)
    recalls = [c["recall"] for c in per_clip.values() if c["recall"] is not None]
    precisions = [c["precision"] for c in per_clip.values() if c["precision"] is not None]
    pooled["macro_recall"] = round(sum(recalls) / len(recalls), 3) if recalls else None
    pooled["macro_recall_n_clips"] = len(recalls)
    pooled["macro_precision"] = round(sum(precisions) / len(precisions), 3) if precisions else None
    pooled["macro_precision_n_clips"] = len(precisions)
    return {"pooled": pooled, "per_clip": per_clip}


def main() -> None:
    out = {}
    for set_name in SETS:
        out[set_name] = {}
        for method in METHODS:
            out[set_name][method] = {"adjudicated": score(method, set_name, True), "as_frozen": score(method, set_name, False)}
    (TRUTH / "methods" / "aggregate.json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    lines = ["# Aggregate scores (generated by `python -m review.aggregate`; do not edit)", ""]
    for set_name in SETS:
        for mode in ("adjudicated", "as_frozen"):
            lines += [f"## {set_name} — {mode}", "", "| method | TP | FPv | FN | FPn | TN | excl | needs_review | P | R | false runs | macro P (n) | macro R (n) |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
            for method in METHODS:
                c = out[set_name][method][mode]["pooled"]
                lines.append(f"| {method.removeprefix('tail_grounded_')} | {c['TP']} | {c['FPv']} | {c['FN']} | {c['FPn']} | {c['TN']} | {c['excluded']} | {c.get('needs_review', 0)} | {c['precision']} | {c['recall']} | {c['false_runs']} | {c['macro_precision']} ({c['macro_precision_n_clips']}) | {c['macro_recall']} ({c['macro_recall_n_clips']}) |")
            lines.append("")
        lines += [f"### {set_name} per clip (adjudicated, v3)", "", "| clip | TP | FPv | FN | FPn | TN | excl | P | R |", "|---|---|---|---|---|---|---|---|---|"]
        for clip, c in out[set_name]["tail_grounded_v3"]["adjudicated"]["per_clip"].items():
            lines.append(f"| {clip} | {c['TP']} | {c['FPv']} | {c['FN']} | {c['FPn']} | {c['TN']} | {c['excluded']} | {c['precision']} | {c['recall']} |")
        lines.append("")
    (TRUTH / "methods" / "aggregate.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
